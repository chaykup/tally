-- Enumerated
CREATE TYPE user_role      AS ENUM ('admin', 'sales', 'customer');
CREATE TYPE order_status   AS ENUM ('pending', 'confirmed', 'cancelled', 'invoiced');
CREATE TYPE invoice_status AS ENUM ('unpaid', 'paid', 'void');

-- Keeps updated_at / last_update_at current
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION set_last_update_at() RETURNS trigger AS $$
BEGIN
    NEW.last_update_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Tables, in dependency order
CREATE TABLE users (
    user_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          user_role NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE products (
    item_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name   VARCHAR(100) NOT NULL,
    unit_price  NUMERIC(10, 2) NOT NULL,
    description VARCHAR(500),
    sku         VARCHAR(32) NOT NULL,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,  -- soft delete; order lines keep referencing old products
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT chk_products_price CHECK (unit_price >= 0)
);

CREATE TABLE warehouses (
    warehouse_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_name VARCHAR(50) NOT NULL,
    location_code  VARCHAR(50) NOT NULL,
    CONSTRAINT uq_warehouses_location UNIQUE (location_code)
);

-- One row per (product, warehouse). Order placement locks these rows with SELECT ... FOR UPDATE.
CREATE TABLE stock (
    inventory_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id           INT NOT NULL,
    warehouse_id      INT NOT NULL,
    quantity          INT NOT NULL DEFAULT 0,
    reorder_threshold INT NOT NULL DEFAULT 0,
    last_update_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_stock_item_warehouse UNIQUE (item_id, warehouse_id),
    CONSTRAINT chk_stock_quantity  CHECK (quantity >= 0),          -- last line of defense against overselling
    CONSTRAINT chk_stock_threshold CHECK (reorder_threshold >= 0),
    CONSTRAINT fk_stock_products   FOREIGN KEY (item_id)      REFERENCES products (item_id),
    CONSTRAINT fk_stock_warehouses FOREIGN KEY (warehouse_id) REFERENCES warehouses (warehouse_id)
);

CREATE TABLE customers (
    customer_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    phone         VARCHAR(32),
    user_id       INT NULL,      -- the customer's own login, if they have one
    sales_rep_id  INT NOT NULL,  -- the sales user who owns this account
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_customers_email     UNIQUE (email),
    CONSTRAINT uq_customers_user      UNIQUE (user_id),
    CONSTRAINT fk_customers_user      FOREIGN KEY (user_id)      REFERENCES users (user_id),
    CONSTRAINT fk_customers_sales_rep FOREIGN KEY (sales_rep_id) REFERENCES users (user_id)
);

CREATE TABLE orders (
    order_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      INT NOT NULL,
    created_by       INT NOT NULL,  -- user who placed the order
    order_date       TIMESTAMPTZ NOT NULL DEFAULT now(),
    delivery_address VARCHAR(255) NOT NULL,
    status           order_status NOT NULL DEFAULT 'pending',
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_orders_customers  FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
    CONSTRAINT fk_orders_created_by FOREIGN KEY (created_by)  REFERENCES users (user_id)
);

CREATE TABLE order_lines (
    line_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     INT NOT NULL,
    item_id      INT NOT NULL,
    warehouse_id INT NOT NULL,  -- warehouse the units were taken from
    quantity     INT NOT NULL,
    unit_price   NUMERIC(10, 2) NOT NULL,  -- price at time of sale, not a live lookup
    CONSTRAINT uq_lines_order_item_wh UNIQUE (order_id, item_id, warehouse_id),
    CONSTRAINT chk_lines_quantity CHECK (quantity > 0),
    CONSTRAINT chk_lines_price    CHECK (unit_price >= 0),
    CONSTRAINT fk_lines_order     FOREIGN KEY (order_id) REFERENCES orders (order_id) ON DELETE CASCADE,
    CONSTRAINT fk_lines_product   FOREIGN KEY (item_id)  REFERENCES products (item_id),
    CONSTRAINT fk_lines_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouses (warehouse_id),
    -- the warehouse must actually stock this product
    CONSTRAINT fk_lines_stock     FOREIGN KEY (item_id, warehouse_id) REFERENCES stock (item_id, warehouse_id)
);

CREATE TABLE invoices (
    invoice_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       INT NOT NULL,
    invoice_number VARCHAR(32) NOT NULL,
    issue_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
    due_date       DATE NOT NULL,
    amount         NUMERIC(12, 2) NOT NULL,
    status         invoice_status NOT NULL DEFAULT 'unpaid',
    paid_at        TIMESTAMPTZ NULL,
    CONSTRAINT uq_invoices_order   UNIQUE (order_id),  -- one invoice per order
    CONSTRAINT uq_invoices_number  UNIQUE (invoice_number),
    CONSTRAINT chk_invoices_amount CHECK (amount >= 0),
    CONSTRAINT fk_invoices_order   FOREIGN KEY (order_id) REFERENCES orders (order_id)
);

-- Indexes
-- Postgres does not index foreign-key columns automatically, so the lookups the API
-- and reports rely on are indexed explicitly. Columns that already lead a UNIQUE
-- constraint (stock.item_id, order_lines.order_id) are covered and skipped.
CREATE INDEX idx_customers_sales_rep  ON customers (sales_rep_id);          -- sales staff: "my customers"
CREATE INDEX idx_orders_customer      ON orders (customer_id);              -- customers: "my orders"
CREATE INDEX idx_orders_created_by    ON orders (created_by);
CREATE INDEX idx_orders_status_date   ON orders (status, order_date);       -- revenue-by-period report
CREATE INDEX idx_orders_date          ON orders (order_date);
CREATE INDEX idx_stock_warehouse      ON stock (warehouse_id);
CREATE INDEX idx_lines_item_warehouse ON order_lines (item_id, warehouse_id); -- top sellers; composite FK

-- Triggers
CREATE TRIGGER trg_products_updated_at  BEFORE UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_customers_updated_at BEFORE UPDATE ON customers
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_orders_updated_at    BEFORE UPDATE ON orders
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_stock_last_update_at BEFORE UPDATE ON stock
    FOR EACH ROW EXECUTE FUNCTION set_last_update_at();
