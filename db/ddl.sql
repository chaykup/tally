-- Tally schema: one PostgreSQL database (Supabase in production, Docker locally),
-- split into one Postgres schema per service.
--
--   accounts   users (logins, roles)                        owned by auth_service
--   inventory  products, warehouses, stock, stock_movements  owned by inventory_service
--   sales      customers, orders, lines, invoices, history   owned by sales_service (transactions)
--   analytics  read-only reporting views                     read by analytics_reader (analytics, Tableau)
--   core       shared trigger helpers                        no service needs direct access
--
-- (The users schema is "accounts", not "auth", because Supabase reserves "auth" for its own users.)
--
-- Every table lives in the same database, so foreign keys cross schemas and order placement
-- (lock stock rows, take the units, write the order) stays a single ACID transaction.
--
-- Service roles are NOLOGIN group roles, so no passwords live in this file. In each
-- environment, create one login per service and add it to its group, for example:
--   CREATE ROLE tally_auth      LOGIN PASSWORD '<secret>' IN ROLE auth_service;
--   CREATE ROLE tally_inventory LOGIN PASSWORD '<secret>' IN ROLE inventory_service;
--   CREATE ROLE tally_sales     LOGIN PASSWORD '<secret>' IN ROLE sales_service;
--   CREATE ROLE tally_analytics LOGIN PASSWORD '<secret>' IN ROLE analytics_reader;
-- Application code should schema-qualify names (inventory.stock, sales.orders, ...).
--
-- History is recorded automatically by triggers, so services cannot forget to write it
-- and cannot edit it afterwards. To label a change, set these for the current transaction
-- before the UPDATE (SET LOCAL, or set_config(name, value, true)):
--   tally.movement_reason  receipt | sale | sale_cancelled | adjustment | transfer | initial
--                          (default: initial for a new stock row, adjustment otherwise)
--   tally.order_id         the order behind a sale or sale_cancelled movement (required for those)
--   tally.user_id          the app user making the change (optional; recorded as performed_by/changed_by)

-- Schemas
CREATE SCHEMA core;
CREATE SCHEMA accounts;
CREATE SCHEMA inventory;
CREATE SCHEMA sales;
CREATE SCHEMA analytics;

-- Service roles. Roles are cluster-wide, so skip any that already exist (for example
-- when the schemas are dropped and this file is run again on the same server).
DO $$
DECLARE
    r text;
BEGIN
    FOREACH r IN ARRAY ARRAY['auth_service', 'inventory_service', 'sales_service', 'analytics_reader'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
            EXECUTE format('CREATE ROLE %I NOLOGIN', r);
        END IF;
    END LOOP;
END
$$;

-- Enumerated
CREATE TYPE accounts.user_role        AS ENUM ('admin', 'sales', 'customer');
CREATE TYPE inventory.movement_reason AS ENUM ('initial', 'receipt', 'sale', 'sale_cancelled', 'adjustment', 'transfer');
CREATE TYPE sales.order_status        AS ENUM ('pending', 'confirmed', 'cancelled', 'invoiced');
CREATE TYPE sales.invoice_status      AS ENUM ('unpaid', 'paid', 'void');

-- Keeps updated_at / last_update_at current
CREATE FUNCTION core.set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION core.set_last_update_at() RETURNS trigger AS $$
BEGIN
    NEW.last_update_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Tables, in dependency order

-- accounts ---------------------------------------------------------------------
CREATE TABLE accounts.users (
    user_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          accounts.user_role NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email UNIQUE (email)
);

-- inventory --------------------------------------------------------------------
CREATE TABLE inventory.products (
    item_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name   VARCHAR(100) NOT NULL,
    unit_price  NUMERIC(10, 2) NOT NULL,
    description VARCHAR(500),
    sku         VARCHAR(32) NOT NULL,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,  -- soft delete; order lines keep referencing old products
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT chk_products_price CHECK (unit_price >= 0)
);

CREATE TABLE inventory.warehouses (
    warehouse_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_name VARCHAR(50) NOT NULL,
    location_code  VARCHAR(50) NOT NULL,
    CONSTRAINT uq_warehouses_location UNIQUE (location_code)
);

-- One row per (product, warehouse). Order placement locks these rows with SELECT ... FOR UPDATE.
CREATE TABLE inventory.stock (
    inventory_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id           INT NOT NULL,
    warehouse_id      INT NOT NULL,
    quantity          INT NOT NULL DEFAULT 0,
    reorder_threshold INT NOT NULL DEFAULT 0,
    last_update_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_stock_item_warehouse UNIQUE (item_id, warehouse_id),
    CONSTRAINT chk_stock_quantity  CHECK (quantity >= 0),          -- last line of defense against overselling
    CONSTRAINT chk_stock_threshold CHECK (reorder_threshold >= 0),
    CONSTRAINT fk_stock_products   FOREIGN KEY (item_id)      REFERENCES inventory.products (item_id),
    CONSTRAINT fk_stock_warehouses FOREIGN KEY (warehouse_id) REFERENCES inventory.warehouses (warehouse_id)
);

-- sales ------------------------------------------------------------------------
CREATE TABLE sales.customers (
    customer_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    phone         VARCHAR(32),
    user_id       INT NULL,      -- the customer's own login, if they have one
    sales_rep_id  INT NOT NULL,  -- the sales user who owns this account
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_customers_email     UNIQUE (email),
    CONSTRAINT uq_customers_user      UNIQUE (user_id),
    CONSTRAINT fk_customers_user      FOREIGN KEY (user_id)      REFERENCES accounts.users (user_id),
    CONSTRAINT fk_customers_sales_rep FOREIGN KEY (sales_rep_id) REFERENCES accounts.users (user_id)
);

CREATE TABLE sales.orders (
    order_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      INT NOT NULL,
    created_by       INT NOT NULL,  -- user who placed the order
    order_date       TIMESTAMPTZ NOT NULL DEFAULT now(),
    delivery_address VARCHAR(255) NOT NULL,
    status           sales.order_status NOT NULL DEFAULT 'pending',
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_orders_customers  FOREIGN KEY (customer_id) REFERENCES sales.customers (customer_id),
    CONSTRAINT fk_orders_created_by FOREIGN KEY (created_by)  REFERENCES accounts.users (user_id)
);

CREATE TABLE sales.order_lines (
    line_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     INT NOT NULL,
    item_id      INT NOT NULL,
    warehouse_id INT NOT NULL,  -- warehouse the units were taken from
    quantity     INT NOT NULL,
    unit_price   NUMERIC(10, 2) NOT NULL,  -- price at time of sale, not a live lookup
    CONSTRAINT uq_lines_order_item_wh UNIQUE (order_id, item_id, warehouse_id),
    CONSTRAINT chk_lines_quantity CHECK (quantity > 0),
    CONSTRAINT chk_lines_price    CHECK (unit_price >= 0),
    CONSTRAINT fk_lines_order     FOREIGN KEY (order_id)     REFERENCES sales.orders (order_id) ON DELETE CASCADE,
    CONSTRAINT fk_lines_product   FOREIGN KEY (item_id)      REFERENCES inventory.products (item_id),
    CONSTRAINT fk_lines_warehouse FOREIGN KEY (warehouse_id) REFERENCES inventory.warehouses (warehouse_id),
    -- the warehouse must actually stock this product
    CONSTRAINT fk_lines_stock     FOREIGN KEY (item_id, warehouse_id) REFERENCES inventory.stock (item_id, warehouse_id)
);

CREATE TABLE sales.invoices (
    invoice_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       INT NOT NULL,
    invoice_number VARCHAR(32) NOT NULL,
    issue_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
    due_date       DATE NOT NULL,
    amount         NUMERIC(12, 2) NOT NULL,
    status         sales.invoice_status NOT NULL DEFAULT 'unpaid',
    paid_at        TIMESTAMPTZ NULL,
    CONSTRAINT uq_invoices_order   UNIQUE (order_id),  -- one invoice per order
    CONSTRAINT uq_invoices_number  UNIQUE (invoice_number),
    CONSTRAINT chk_invoices_amount CHECK (amount >= 0),
    CONSTRAINT fk_invoices_order   FOREIGN KEY (order_id) REFERENCES sales.orders (order_id)
);

-- History tables (written only by triggers) -------------------------------------

-- Every change to stock.quantity, with the level after it: the source for inventory-over-time charts.
-- Because movements reference their stock row, a stock row with history cannot be deleted;
-- set its quantity to 0 instead. Likewise an order that moved stock cannot be deleted; cancel it.
CREATE TABLE inventory.stock_movements (
    movement_id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    item_id         INT NOT NULL,
    warehouse_id    INT NOT NULL,
    quantity_change INT NOT NULL,   -- positive = units in, negative = units out
    quantity_after  INT NOT NULL,   -- stock level once this movement applied
    reason          inventory.movement_reason NOT NULL,
    order_id        INT NULL,       -- set for sale / sale_cancelled
    performed_by    INT NULL,       -- app user, from tally.user_id
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_movements_after CHECK (quantity_after >= 0),
    CONSTRAINT chk_movements_order CHECK (reason NOT IN ('sale', 'sale_cancelled') OR order_id IS NOT NULL),
    CONSTRAINT fk_movements_stock  FOREIGN KEY (item_id, warehouse_id) REFERENCES inventory.stock (item_id, warehouse_id),
    CONSTRAINT fk_movements_order  FOREIGN KEY (order_id)     REFERENCES sales.orders (order_id),
    CONSTRAINT fk_movements_user   FOREIGN KEY (performed_by) REFERENCES accounts.users (user_id)
);

-- Every status an order has been in, including the first (from_status is NULL on creation).
CREATE TABLE sales.order_status_history (
    history_id  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id    INT NOT NULL,
    from_status sales.order_status NULL,
    to_status   sales.order_status NOT NULL,
    changed_by  INT NULL,          -- app user, from tally.user_id
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_history_changed CHECK (from_status IS DISTINCT FROM to_status),
    CONSTRAINT fk_history_order    FOREIGN KEY (order_id)   REFERENCES sales.orders (order_id) ON DELETE CASCADE,
    CONSTRAINT fk_history_user     FOREIGN KEY (changed_by) REFERENCES accounts.users (user_id)
);

-- Indexes
-- Postgres does not index foreign-key columns automatically, so the lookups the API
-- and reports rely on are indexed explicitly. Columns that already lead a UNIQUE
-- constraint (stock.item_id, order_lines.order_id) are covered and skipped.
CREATE INDEX idx_customers_sales_rep  ON sales.customers (sales_rep_id);            -- sales staff: "my customers"
CREATE INDEX idx_orders_customer      ON sales.orders (customer_id);                -- customers: "my orders"
CREATE INDEX idx_orders_created_by    ON sales.orders (created_by);
CREATE INDEX idx_orders_status_date   ON sales.orders (status, order_date);         -- revenue-by-period report
CREATE INDEX idx_orders_date          ON sales.orders (order_date);
CREATE INDEX idx_stock_warehouse      ON inventory.stock (warehouse_id);
CREATE INDEX idx_lines_item_warehouse ON sales.order_lines (item_id, warehouse_id); -- top sellers; composite FK
CREATE INDEX idx_movements_stock_time ON inventory.stock_movements (item_id, warehouse_id, created_at); -- level on a date
CREATE INDEX idx_movements_order      ON inventory.stock_movements (order_id);
CREATE INDEX idx_history_order_time   ON sales.order_status_history (order_id, changed_at);

-- History triggers
-- SECURITY DEFINER: they run as the schema owner, so they can write the history tables
-- even though no service role has INSERT on them.

CREATE FUNCTION inventory.record_stock_movement() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
    v_reason inventory.movement_reason := COALESCE(
        NULLIF(current_setting('tally.movement_reason', true), ''),
        CASE WHEN TG_OP = 'INSERT' THEN 'initial' ELSE 'adjustment' END)::inventory.movement_reason;
    v_order  int := NULLIF(current_setting('tally.order_id', true), '')::int;
    v_user   int := NULLIF(current_setting('tally.user_id',  true), '')::int;
BEGIN
    INSERT INTO inventory.stock_movements
        (item_id, warehouse_id, quantity_change, quantity_after, reason, order_id, performed_by)
    VALUES
        (NEW.item_id, NEW.warehouse_id,
         NEW.quantity - CASE WHEN TG_OP = 'INSERT' THEN 0 ELSE OLD.quantity END,
         NEW.quantity, v_reason, v_order, v_user);
    RETURN NULL;
END;
$$;

CREATE FUNCTION sales.record_order_status() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    INSERT INTO sales.order_status_history (order_id, from_status, to_status, changed_by)
    VALUES (NEW.order_id,
            CASE WHEN TG_OP = 'UPDATE' THEN OLD.status END,
            NEW.status,
            NULLIF(current_setting('tally.user_id', true), '')::int);
    RETURN NULL;
END;
$$;

-- Triggers
CREATE TRIGGER trg_products_updated_at  BEFORE UPDATE ON inventory.products
    FOR EACH ROW EXECUTE FUNCTION core.set_updated_at();
CREATE TRIGGER trg_customers_updated_at BEFORE UPDATE ON sales.customers
    FOR EACH ROW EXECUTE FUNCTION core.set_updated_at();
CREATE TRIGGER trg_orders_updated_at    BEFORE UPDATE ON sales.orders
    FOR EACH ROW EXECUTE FUNCTION core.set_updated_at();
CREATE TRIGGER trg_stock_last_update_at BEFORE UPDATE ON inventory.stock
    FOR EACH ROW EXECUTE FUNCTION core.set_last_update_at();

CREATE TRIGGER trg_stock_movement_insert AFTER INSERT ON inventory.stock
    FOR EACH ROW EXECUTE FUNCTION inventory.record_stock_movement();
CREATE TRIGGER trg_stock_movement_update AFTER UPDATE OF quantity ON inventory.stock
    FOR EACH ROW WHEN (OLD.quantity IS DISTINCT FROM NEW.quantity)
    EXECUTE FUNCTION inventory.record_stock_movement();
CREATE TRIGGER trg_order_status_insert AFTER INSERT ON sales.orders
    FOR EACH ROW EXECUTE FUNCTION sales.record_order_status();
CREATE TRIGGER trg_order_status_update AFTER UPDATE OF status ON sales.orders
    FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
    EXECUTE FUNCTION sales.record_order_status();

-- Analytics views
-- Plain views, so they are always current. They run with the owner's privileges, which
-- lets analytics_reader query them without any access to the underlying tables.
-- Revenue counts orders that are 'confirmed' or 'invoiced'; 'pending' and 'cancelled' do not.
-- Calendar buckets use UTC so results do not depend on the client's time zone.

-- One row per order line with everything joined in: the main data source for sales charts.
-- sales_rep_* is the customer's current rep, not necessarily the rep at the time of the order.
CREATE VIEW analytics.order_line_facts AS
SELECT
    o.order_id,
    o.order_date,
    (o.order_date AT TIME ZONE 'UTC')::date     AS order_day_utc,
    o.status::text                              AS order_status,
    o.status IN ('confirmed', 'invoiced')       AS counts_as_revenue,
    c.customer_id,
    c.customer_name,
    rep.user_id                                 AS sales_rep_id,
    rep.email                                   AS sales_rep_email,
    p.item_id,
    p.sku,
    p.item_name,
    w.warehouse_id,
    w.warehouse_name,
    w.location_code,
    l.quantity,
    l.unit_price,
    l.quantity * l.unit_price                   AS line_total
FROM sales.order_lines     l
JOIN sales.orders          o   ON o.order_id     = l.order_id
JOIN sales.customers       c   ON c.customer_id  = o.customer_id
JOIN accounts.users        rep ON rep.user_id    = c.sales_rep_id
JOIN inventory.products    p   ON p.item_id      = l.item_id
JOIN inventory.warehouses  w   ON w.warehouse_id = l.warehouse_id;

CREATE VIEW analytics.revenue_by_month AS
SELECT
    date_trunc('month', order_day_utc)::date AS month,
    count(DISTINCT order_id)                 AS order_count,
    sum(quantity)                            AS units_sold,
    sum(line_total)                          AS revenue
FROM analytics.order_line_facts
WHERE counts_as_revenue
GROUP BY 1;

CREATE VIEW analytics.top_products AS
SELECT
    item_id,
    sku,
    item_name,
    count(DISTINCT order_id) AS order_count,
    sum(quantity)            AS units_sold,
    sum(line_total)          AS revenue
FROM analytics.order_line_facts
WHERE counts_as_revenue
GROUP BY item_id, sku, item_name;

-- Active products at or below their reorder threshold, per warehouse.
CREATE VIEW analytics.low_stock AS
SELECT
    s.item_id,
    p.sku,
    p.item_name,
    s.warehouse_id,
    w.warehouse_name,
    s.quantity,
    s.reorder_threshold,
    s.reorder_threshold - s.quantity AS shortfall,
    s.last_update_at
FROM inventory.stock      s
JOIN inventory.products   p ON p.item_id      = s.item_id
JOIN inventory.warehouses w ON w.warehouse_id = s.warehouse_id
WHERE p.is_active
  AND s.quantity <= s.reorder_threshold;

CREATE VIEW analytics.unpaid_invoices AS
SELECT
    i.invoice_id,
    i.invoice_number,
    i.order_id,
    c.customer_id,
    c.customer_name,
    i.amount,
    i.issue_date,
    i.due_date,
    i.due_date < current_date                AS is_overdue,
    greatest(current_date - i.due_date, 0)   AS days_overdue
FROM sales.invoices  i
JOIN sales.orders    o ON o.order_id    = i.order_id
JOIN sales.customers c ON c.customer_id = o.customer_id
WHERE i.status = 'unpaid';

-- One row per stock movement with names joined in.
CREATE VIEW analytics.stock_movement_facts AS
SELECT
    m.movement_id,
    m.created_at,
    (m.created_at AT TIME ZONE 'UTC')::date AS movement_day_utc,
    m.item_id,
    p.sku,
    p.item_name,
    m.warehouse_id,
    w.warehouse_name,
    m.reason::text                          AS reason,
    m.quantity_change,
    m.quantity_after,
    m.order_id
FROM inventory.stock_movements m
JOIN inventory.products        p ON p.item_id      = m.item_id
JOIN inventory.warehouses      w ON w.warehouse_id = m.warehouse_id;

-- Closing stock level for every product, warehouse and UTC day, from the first movement
-- through today. Days without movements carry the previous level forward, so this charts
-- directly as a continuous line. reorder_threshold is the current threshold.
CREATE VIEW analytics.daily_stock_levels AS
SELECT
    s.item_id,
    p.sku,
    p.item_name,
    s.warehouse_id,
    w.warehouse_name,
    d.day::date          AS day,
    lvl.quantity_after   AS closing_quantity,
    s.reorder_threshold,
    lvl.quantity_after <= s.reorder_threshold AS at_or_below_threshold
FROM inventory.stock      s
JOIN inventory.products   p ON p.item_id      = s.item_id
JOIN inventory.warehouses w ON w.warehouse_id = s.warehouse_id
CROSS JOIN LATERAL generate_series(
    (SELECT min(m.created_at AT TIME ZONE 'UTC')::date
       FROM inventory.stock_movements m
      WHERE m.item_id = s.item_id AND m.warehouse_id = s.warehouse_id),
    (now() AT TIME ZONE 'UTC')::date,
    interval '1 day') AS d(day)
CROSS JOIN LATERAL (
    SELECT m.quantity_after
      FROM inventory.stock_movements m
     WHERE m.item_id = s.item_id AND m.warehouse_id = s.warehouse_id
       AND m.created_at < (d.day + interval '1 day') AT TIME ZONE 'UTC'
     ORDER BY m.created_at DESC, m.movement_id DESC
     LIMIT 1) AS lvl;

-- Every order status change.
CREATE VIEW analytics.order_status_changes AS
SELECT
    h.history_id,
    h.order_id,
    h.from_status::text                     AS from_status,
    h.to_status::text                       AS to_status,
    h.changed_at,
    (h.changed_at AT TIME ZONE 'UTC')::date AS changed_day_utc,
    h.changed_by
FROM sales.order_status_history h;

-- One row per order: when it first reached each status and how long that took.
CREATE VIEW analytics.order_cycle_times AS
SELECT
    o.order_id,
    o.order_date,
    o.status::text AS current_status,
    min(h.changed_at) FILTER (WHERE h.to_status = 'confirmed') AS confirmed_at,
    min(h.changed_at) FILTER (WHERE h.to_status = 'invoiced')  AS invoiced_at,
    min(h.changed_at) FILTER (WHERE h.to_status = 'cancelled') AS cancelled_at,
    round(extract(epoch FROM min(h.changed_at) FILTER (WHERE h.to_status = 'confirmed') - o.order_date) / 3600, 2)
        AS hours_to_confirm,
    round(extract(epoch FROM min(h.changed_at) FILTER (WHERE h.to_status = 'invoiced') - o.order_date) / 3600, 2)
        AS hours_to_invoice
FROM sales.orders o
LEFT JOIN sales.order_status_history h ON h.order_id = o.order_id
GROUP BY o.order_id, o.order_date, o.status;

-- Privileges
-- Each service writes only its own schema. History tables are read-only to everyone;
-- only the triggers above write them. Default privileges cover tables and views added
-- to these schemas later by the same owner, so new objects get the same access.

-- accounts: owned by auth_service. Other services can look users up (for foreign keys,
-- "my customers", role checks) but cannot see password hashes or change users.
GRANT USAGE ON SCHEMA accounts TO auth_service, inventory_service, sales_service;
GRANT SELECT, INSERT, UPDATE, DELETE ON accounts.users TO auth_service;
ALTER DEFAULT PRIVILEGES IN SCHEMA accounts
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO auth_service;
GRANT SELECT (user_id, email, role, created_at) ON accounts.users TO inventory_service, sales_service;

-- inventory: owned by inventory_service. sales_service can read the catalog and stock, and may
-- change stock.quantity only, which is what order placement needs (UPDATE on a column is
-- also what allows SELECT ... FOR UPDATE).
GRANT USAGE ON SCHEMA inventory TO inventory_service, sales_service;
GRANT SELECT, INSERT, UPDATE, DELETE ON inventory.products, inventory.warehouses, inventory.stock
    TO inventory_service;
GRANT SELECT ON inventory.stock_movements TO inventory_service;
ALTER DEFAULT PRIVILEGES IN SCHEMA inventory
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO inventory_service;
GRANT SELECT ON inventory.products, inventory.warehouses, inventory.stock, inventory.stock_movements
    TO sales_service;
GRANT UPDATE (quantity) ON inventory.stock TO sales_service;

-- sales: owned by sales_service.
GRANT USAGE ON SCHEMA sales TO sales_service;
GRANT SELECT, INSERT, UPDATE, DELETE ON sales.customers, sales.orders, sales.order_lines, sales.invoices
    TO sales_service;
GRANT SELECT ON sales.order_status_history TO sales_service;
ALTER DEFAULT PRIVILEGES IN SCHEMA sales
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO sales_service;

-- analytics: read-only views; analytics_reader has no direct access to any base table.
GRANT USAGE ON SCHEMA analytics TO analytics_reader;
GRANT SELECT ON ALL TABLES IN SCHEMA analytics TO analytics_reader;
ALTER DEFAULT PRIVILEGES IN SCHEMA analytics
    GRANT SELECT ON TABLES TO analytics_reader;
